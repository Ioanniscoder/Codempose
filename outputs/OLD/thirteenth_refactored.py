def build_score_data() -> Dict[str, Dict]:
    """
    Execute the composition plan defined in the Composer's Workspace above.
    
    This function:
    1. Parses all LilyPond snippets from Station 1
    2. Generates TinyNotation validation strings (Station 2)
    3. Displays real-time validation feedback (LilyPond vs TinyNotation)
    4. Generates transformations on-demand
    5. Converts transformed music back to LilyPond format
    6. Populates Station 2 placeholders
    7. Assembles the final score using Blueprint Strings (Station 3)
    
    Returns:
        Dictionary with 'metadata' and 'parts' keys
    """
    print("\n" + "="*70)
    print("THIRTEENTH STUDY: Complete Parser Feature Showcase")
    print("="*70)
    
    # ========================================================================
    # STEP 1: PARSE LILYPOND SNIPPETS & GENERATE TINYNOTATION
    # ========================================================================
    
    print("\n[STEP 1: Parsing LilyPond snippets and generating TinyNotation...]")
    print("\n" + "-"*70)
    print("REAL-TIME VALIDATION: LilyPond → TinyNotation Comparison")
    print("-"*70)
    
    # Parse Theme A
    parsed_a = parse_lilypond_to_data(THEME_A_LILY, part_name='ThemeA')
    theme_a_events = parsed_a.get('parts', {}).get('ThemeA', [])
    theme_a_part = data_to_part(theme_a_events, parsed_a.get('metadata', {}))
    
    print("\n📝 THEME_A:")
    print(f"   LilyPond Input:  {THEME_A_LILY[:60]}...")
    print(f"   TinyNotation:    {THEME_A_TINY[:60]}...")
    print(f"   ✓ Parsed: {len(theme_a_events)} events")
    
    # Parse Intermezzo (contains chords - critical for chord parsing validation)
    parsed_intermezzo = parse_lilypond_to_data(INTERMEZZO_LILY, part_name='Intermezzo')
    intermezzo_events = parsed_intermezzo.get('parts', {}).get('Intermezzo', [])
    intermezzo_part = data_to_part(intermezzo_events, parsed_intermezzo.get('metadata', {}))
    
    print("\n📝 INTERMEZZO (Chords):")
    print(f"   LilyPond Input:  {INTERMEZZO_LILY.strip()[:60]}...")
    print(f"   TinyNotation:    {INTERMEZZO_TINY[:60]}...")
    print(f"   ✓ Parsed: {len(intermezzo_events)} events")
    if len(intermezzo_events) > 0 and intermezzo_events[0].get('type') == 'chord':
        print(f"   ✓ Chord detected: {intermezzo_events[0].get('pitches', [])}")
    
    print("\n" + "-"*70)
    print("✅ Validation Complete: All snippets parsed successfully")
    print("   (Compare TinyNotation output above with expected Station 2 strings)")
    print("-"*70)
    
    # ========================================================================
    # STEP 2: GENERATE TRANSFORMATIONS ON-DEMAND
    # ========================================================================
    
    print("\n[STEP 2: Generating transformations...]")
    
    # Generate Theme A variations
    theme_a_transposed_part = transpose_part(theme_a_part, 'P5')
    theme_a_inverted_part = invert_part(theme_a_part, 'C4')
    
    # Harmonize and transpose down an octave for better chord range
    theme_a_harmony_part = chordify_part(theme_a_part)
    theme_a_harmony_part = transpose_part(theme_a_harmony_part, 'P-8')
    
    # Extract event data
    theme_a_transposed = extract_data_from_part(theme_a_transposed_part)
    theme_a_inverted = extract_data_from_part(theme_a_inverted_part)
    theme_a_harmony = extract_data_from_part(theme_a_harmony_part)
    
    print(f"   ✓ Generated THEME_A_TRANSPOSED (P5)")
    print(f"   ✓ Generated THEME_A_INVERTED (C4 center)")
    print(f"   ✓ Generated THEME_A_HARMONIZED (chordified, -P8)")
    
    # ========================================================================
    # STEP 3: CONVERT TRANSFORMATIONS BACK TO LILYPOND FORMAT
    # ========================================================================
    
    print("\n[STEP 3: Converting transformations to LilyPond format...]")
    
    # Metadata for snippet conversion
    snippet_metadata = {
        'time_signature': '4/4',
        'key_signature': {'tonic': 'c', 'mode': 'major'}
    }
    
    # Convert to LilyPond strings and populate Station 2 placeholders
    global THEME_A_TRANSPOSED_LILY, THEME_A_INVERTED_LILY, THEME_A_HARMONIZED_LILY
    
    THEME_A_TRANSPOSED_LILY = events_to_lily(theme_a_transposed, snippet_metadata)
    print(f"   ✓ Populated THEME_A_TRANSPOSED_LILY")
    
    THEME_A_INVERTED_LILY = events_to_lily(theme_a_inverted, snippet_metadata)
    print(f"   ✓ Populated THEME_A_INVERTED_LILY")
    
    THEME_A_HARMONIZED_LILY = events_to_lily(theme_a_harmony, snippet_metadata)
    print(f"   ✓ Populated THEME_A_HARMONIZED_LILY")
    
    # ========================================================================
    # STEP 4: BUILD SNIPPETS LIBRARY FOR BLUEPRINT FRAMEWORK
    # ========================================================================
    
    print("\n[STEP 4: Building snippets library...]")
    
    # Internal library for blueprint framework (temporary, function-scoped)
    SNIPPETS = {
        'THEME_A': theme_a_events,
        'THEME_A_TRANSPOSED': theme_a_transposed,
        'THEME_A_INVERTED': theme_a_inverted,
        'THEME_A_HARMONIZED': theme_a_harmony,
        'INTERMEZZO': intermezzo_events,
    }
    
    print(f"   ✓ Library contains {len(SNIPPETS)} snippets")
    for name in SNIPPETS.keys():
        print(f"      - {name}")
    
    # ========================================================================
    # STEP 5: ASSEMBLE SCORE USING BLUEPRINT STRINGS
    # ========================================================================
    
    print("\n[STEP 5: Assembling score with Blueprint String Framework...]")
    
    # Basic metadata for score
    basic_metadata = {
        'title': TITLE,
        'composer': COMPOSER,
        'time_signature': '4/4',
        'key_signature': {'tonic': 'c', 'mode': 'major'}
    }
    
    # Build score using blueprint strings from Station 3
    score_result = build_score_from_blueprint(
        VOICE_STAVE_DEF,
        VOICE_STAVE_DATA,
        SNIPPETS,
        basic_metadata
    )
    
    return score_result


