# ============================================================================
# STATION 2: VALIDATING & GENERATED INPUT (The Reference)
# ============================================================================
#
# AUTO-GENERATED VALIDATION STRINGS:
# These TinyNotation strings are generated by the parser during execution.
# They serve as a critical real-time validation tool for pitch resolution.
# Compare these with the console output to verify octave correctness.
#
# PROGRAMMATICALLY GENERATED SNIPPETS:
# Placeholders for snippets created by custom transformations.
# These will be populated during execution by build_score_data().

# --- TinyNotation Validation Strings (Auto-Generated) ---
# These are populated during parsing and displayed in console output
THEME_A_TINY = "tinynotation: 4/4 c4 d8 e8 f8 e4~ e4 g16grace a2 b8 c8 d8 c4~ c4 e8 f8 g8 f4 e2 d4 c16grace e2~ e4 r2"
INTERMEZZO_TINY = "tinynotation: 4/4 <c e g>2 <d f a>2 <e g b>2 <f a c>2"

# --- Generated Snippet Placeholders ---
# These will be populated by build_score_data() after transformations are applied
THEME_A_TRANSPOSED_LILY = None  # Will be generated: THEME_A transposed up P5
THEME_A_INVERTED_LILY = None    # Will be generated: THEME_A inverted around C4
THEME_A_HARMONIZED_LILY = None  # Will be generated: THEME_A chordified and transposed down octave


# ============================================================================
# STATION 3: STRUCTURING INPUT (The Blueprint)
# ============================================================================
#
# Blueprint String Framework: Declarative score assembly using intuitive delimiters.
#
# DELIMITER REFERENCE:
#   ; (semicolon)  = Section separator (like double barlines)
#   & (ampersand)  = Staff separator (vertical stacking)
#   | (pipe)       = Snippet concatenator (horizontal "then")
#   , (comma)      = Voice separator (multi-voice staves)
#   'r'            = Auto-generate rests matching section duration
#
# READ THIS LIKE A SCORE TABLE:
#   - Each line (ending with ;) is a section
#   - Before &: What upper staff plays
#   - After &: What lower staff plays

# Layout: Define which staves exist
VOICE_STAVE_DEF = "UpperStaff & LowerStaff"

# Content: Define what each staff plays in each section
VOICE_STAVE_DATA = """
    THEME_A & r;
    r & INTERMEZZO;
    THEME_A_TRANSPOSED & r;
    r & INTERMEZZO;
    THEME_A_INVERTED & r;
    r & INTERMEZZO;
    THEME_A_HARMONIZED & r
"""


