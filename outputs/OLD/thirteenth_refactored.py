# Theme A: Tuplets, Ties, Grace Notes
THEME_A_LILY = r"""
\relative c' {
    \time 4/4
    \key c \major
    \tempo 4=120
    c4 [d e f]8 e4~ e4 |
    ~g16 a2(p) [b c d]8 c4 |
    [e f g]8 f4 e2 d4 |
    ~c16 e2 e4 r1
}
"""

